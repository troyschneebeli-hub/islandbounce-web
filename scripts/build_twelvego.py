#!/usr/bin/env python3
"""
Builds data/twelvego.js from the 12Go capture spreadsheet (scripts/12go-master-routes.xlsx,
sheet "Master Routes"). The listings were read from the booking page for one date and are
treated as the SAME every day (Troy's decision). Re-capture and re-run about monthly.

    python3 scripts/build_twelvego.py [scripts/12go-master-routes.xlsx]

Only 'Scheduled boat' rows with a departure time are published. Transfer packages, flights,
private charters and hotel pickup packages stay in the spreadsheet only.
Rows are published as "unconfirmed" and skipped where an operator we have confirmed
already has sailings on the same port pair, so confirmed data is never contradicted.
"""
import json, re, sys, os
import openpyxl

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "12go-master-routes.xlsx")
OUT = os.path.join(HERE, "..", "data", "twelvego.js")
TT = os.path.join(HERE, "..", "data", "timetables.js")

PORTS = {"sanur": "Sanur", "padang-bai": "Padang Bai", "serangan": "Serangan", "benoa-nusa-dua": "Benoa / Nusa Dua",
         "gili-trawangan": "Gili Trawangan", "gili-air": "Gili Air", "gili-meno": "Gili Meno",
         "bangsal": "Bangsal (Lombok)", "nusa-penida": "Nusa Penida", "nusa-lembongan": "Nusa Lembongan"}
# 12Go spelling -> the name we already use for the same company
OPS = {"Ekajaya Fast Ferry": "Eka Jaya Fast Boat", "BlueWater Express": "Blue Water Express",
       "Gili Gili Fastboat": "Gili Gili Fast Boat", "Gili Getaway": "Gili Getaway"}
CAPTURED = "2026-10-15"
SOURCE = "12Go booking page (listings for 20 Oct 2026, assumed daily)"

def mins(t): h, m = t.split(":"); return int(h) * 60 + int(m)
def hhmm(n): n %= 1440; return f"{n // 60:02d}:{n % 60:02d}"
def key(s): return re.sub(r"[^a-z0-9]", "", s.lower())
def slugify(s): return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", s.lower())).strip("-")

# operator+pair combinations we already have confirmed data for
confirmed = set()
for line in open(TT, encoding="utf-8"):
    line = line.strip().rstrip(",")
    if line.startswith('{"id"'):
        s = json.loads(line)
        if s["confidence"] != "unconfirmed":
            confirmed.add((key(s["operator"]), s["from"], s["to"]))

ws = openpyxl.load_workbook(SRC, data_only=True)["Master Routes"]
out, seen, skipped = [], set(), 0
for r in list(ws.iter_rows(min_row=2, values_only=True)):
    frm, to, op, cls, cat, _typ, dep, arr, dur, price, isfrom, rating, _d = r[:13]
    if cat != "Scheduled boat" or not dep or not arr or op.startswith("("):
        continue
    if mins(dep) < 5 * 60:  # 12Go lists a few 01:30 entries that look like time-zone slips
        skipped += 1; continue
    op = OPS.get(op, op); a, b = PORTS[frm], PORTS[to]
    if (key(op), a, b) in confirmed:
        skipped += 1; continue
    k = (key(op), a, b, dep)
    if k in seen: continue
    seen.add(k)
    out.append({"id": f"12go-{slugify(op)}-{slugify(a)}-{slugify(b)}-{dep.replace(':', '-')}",
                "operator": op, "from": a, "to": b, "checkIn": hhmm(mins(dep) - 60), "departs": dep, "arrives": arr,
                "via": [], "kind": "direct", "season": "Daily (assumed)", "validFrom": None, "validTo": None,
                "source": SOURCE, "verified": CAPTURED, "flag": None, "confidence": "unconfirmed",
                "note": "From a booking-site listing", "boat": cls or None, "price": round(float(price))})
out.sort(key=lambda s: (s["from"], s["to"], s["departs"], s["operator"]))
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// AUTO-GENERATED by scripts/build_twelvego.py from scripts/12go-master-routes.xlsx. Do not edit by hand.\n")
    f.write("// Listings read from the 12Go booking page for one date and assumed identical every day. Re-capture roughly monthly.\n")
    f.write(f'export const TWELVEGO_CAPTURED = "{CAPTURED}";\n\nexport const TWELVEGO_SAILINGS = [\n')
    f.write(",\n".join("  " + json.dumps(s, ensure_ascii=False) for s in out))
    f.write("\n];\n")
print(len(out), "sailings written;", skipped, "skipped")
